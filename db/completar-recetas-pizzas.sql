-- Completa recetas que faltan para las pizzas indicadas y productos de pizza sin receta.
-- Las cantidades están expresadas en kg/litros por unidad de producto. Son valores base de trabajo:
-- confirmar las cantidades reales de cocina antes de usar en producción.
-- En combos, NO se carga una receta completa de pizza fija porque el cliente elige la pizza:
-- el pedido descuenta la receta de cada pizza elegida. Este script solo agrega al combo
-- insumos de complementos fijos reconocibles en su descripción (p. ej. alitas o palitos de ajo).
BEGIN;

CREATE TABLE IF NOT EXISTS receta_insumos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id integer NOT NULL REFERENCES productos(id),
    insumo_id integer NOT NULL REFERENCES insumos(id),
    cantidad numeric(19,6) NOT NULL CHECK (cantidad > 0),
    UNIQUE (producto_id, insumo_id)
);

-- Nombres de insumos normalizados para admitir variaciones de tildes/códigos.
WITH insumo AS (
    SELECT id, lower(trim(nombre)) AS nombre FROM insumos
),
pizzas AS (
    SELECT p.id,
           lower(coalesce(p.nombre,'') || ' ' || coalesce(p.descripcion,'')) AS texto,
           lower(coalesce(p.nombre,'')) AS nombre,
           CASE
             WHEN lower(coalesce(p.tamano,'')) LIKE '%personal%' THEN 0.135::numeric
             WHEN lower(coalesce(p.tamano,'')) LIKE '%mediana%' THEN 0.220::numeric
             ELSE 0.300::numeric
           END AS harina
    FROM productos p
    LEFT JOIN categorias c ON c.id=p.categoria_id
    WHERE (
        lower(coalesce(c.codigo,'')) IN ('clasicas','clasica','especiales','especial','principales','principal')
        OR (lower(coalesce(c.codigo,'')) IN ('promociones','promocion')
            AND lower(coalesce(p.tamano,'')) LIKE '%personal%')
        OR lower(coalesce(p.nombre,'')) LIKE ANY (ARRAY[
            '%la constea%','%la brava%','%la consentida%','%martes de pizza%',
            '%el último secreto%','%el ultimo secreto%','%la reina del bosque%',
            '%promoción familiar%','%promocion familiar%','%promoción hawaiana%','%promocion hawaiana%',
            '%la banda caleta%','%alianza prohibida%','%la mesa de los cómplices%',
            '%la mesa de los complices%','%pacto de medianoche%','%reunión clandestina%',
            '%reunion clandestina%'
        ])
    )
    AND lower(coalesce(c.codigo,'')) NOT IN ('combos','combo')
),
faltantes AS (
    -- Incluye recetas vacías y parciales: solo se insertarán pares producto/insumo que falten.
    SELECT p.* FROM pizzas p
),
base AS (
    SELECT f.id producto_id, i.id insumo_id, x.cantidad
    FROM faltantes f
    CROSS JOIN LATERAL (VALUES
       ('harina de trigo', f.harina),
       ('agua filtrada', f.harina * 0.60),
       ('levadura', f.harina * 0.0167),
       ('sal', f.harina * 0.020),
       ('aceite de oliva', f.harina * 0.0333),
       ('queso mozzarella', f.harina * 0.667),
       ('salsa de tomate', f.harina * 0.400)
    ) x(nombre, cantidad)
    JOIN insumo i ON i.nombre=x.nombre
),
-- Ingredientes adicionales por pizza, usando el nombre y descripción disponibles en Neon.
toppings AS (
    SELECT f.id producto_id, i.id insumo_id, x.cantidad
    FROM faltantes f
    CROSS JOIN LATERAL (VALUES
      ('Pepperoni Laminado', 0.090::numeric,
        f.texto LIKE '%pepperoni%' OR f.nombre LIKE '%la brava%' OR f.nombre LIKE '%martes de pizza%' OR f.nombre LIKE '%la constea%' OR f.nombre LIKE '%alianza prohibida%' OR f.nombre LIKE '%reunión clandestina%' OR f.nombre LIKE '%reunion clandestina%'),
      ('Jamón', 0.080::numeric,
        f.texto LIKE '%jamon%' OR f.texto LIKE '%jamón%' OR f.texto LIKE '%hawaiana%' OR f.nombre LIKE '%la consentida%'),
      ('Piña', 0.100::numeric,
        f.texto LIKE '%piña%' OR f.texto LIKE '%pina%' OR f.texto LIKE '%hawaiana%' OR f.nombre LIKE '%la consentida%'),
      ('Tocino', 0.050::numeric,
        f.texto LIKE '%tocino%' OR f.texto LIKE '%bacon%' OR f.nombre LIKE '%el último secreto%' OR f.nombre LIKE '%el ultimo secreto%' OR f.nombre LIKE '%la banda caleta%' OR f.nombre LIKE '%la mesa de los cómplices%' OR f.nombre LIKE '%la mesa de los complices%' OR f.nombre LIKE '%pacto de medianoche%'),
      ('Carne de Res', 0.080::numeric,
        f.texto LIKE '%carne%' OR f.nombre LIKE '%el último secreto%' OR f.nombre LIKE '%el ultimo secreto%' OR f.nombre LIKE '%la banda caleta%' OR f.nombre LIKE '%la mesa de los cómplices%' OR f.nombre LIKE '%la mesa de los complices%' OR f.nombre LIKE '%pacto de medianoche%'),
      ('Champiñones', 0.060::numeric,
        f.texto LIKE '%champi%' OR f.nombre LIKE '%la reina del bosque%'),
      ('Pimiento', 0.050::numeric,
        f.texto LIKE '%pimiento%' OR f.nombre LIKE '%la reina del bosque%'),
      ('Aceituna', 0.025::numeric,
        f.texto LIKE '%aceituna%' OR f.nombre LIKE '%la reina del bosque%'),
      ('Albahaca', 0.003::numeric,
        f.texto LIKE '%albahaca%' OR f.nombre LIKE '%la reina del bosque%'),
      ('Alitas de Pollo', 0.080::numeric,
        f.texto LIKE '%pollo%')
    ) x(nombre, cantidad, aplica)
    JOIN insumo i ON lower(i.nombre)=lower(x.nombre)
    WHERE x.aplica
),
lineas AS (
    SELECT * FROM base WHERE cantidad > 0
    UNION ALL
    SELECT * FROM toppings WHERE cantidad > 0
)
INSERT INTO receta_insumos(producto_id, insumo_id, cantidad)
SELECT producto_id, insumo_id, cantidad FROM lineas
ON CONFLICT (producto_id, insumo_id) DO NOTHING;

-- Recetas de acompañamientos que pueden venir incluidos en combos.
-- El backend descuenta estos componentes según la descripción del combo, sin cobrarlos aparte.
WITH acompanamientos AS (
    SELECT p.id, lower(p.nombre) AS nombre
    FROM productos p
    LEFT JOIN categorias c ON c.id=p.categoria_id
    WHERE lower(coalesce(c.codigo,'')) IN ('acompanamientos','acompañamientos')
      AND (lower(p.nombre) LIKE '%alitas bbq%' OR lower(p.nombre) LIKE '%palitos de ajo%')
),
lineas AS (
    SELECT a.id AS producto_id, i.id AS insumo_id, x.cantidad
    FROM acompanamientos a
    CROSS JOIN LATERAL (VALUES
      ('Alitas de Pollo', 0.450::numeric, a.nombre LIKE '%alitas bbq%'),
      ('Salsa BBQ', 0.080::numeric, a.nombre LIKE '%alitas bbq%'),
      ('Sal', 0.004::numeric, a.nombre LIKE '%alitas bbq%'),
      ('Harina de Trigo', 0.150::numeric, a.nombre LIKE '%palitos de ajo%'),
      ('Agua Filtrada', 0.090::numeric, a.nombre LIKE '%palitos de ajo%'),
      ('Levadura', 0.003::numeric, a.nombre LIKE '%palitos de ajo%'),
      ('Sal', 0.003::numeric, a.nombre LIKE '%palitos de ajo%'),
      ('Mantequilla', 0.030::numeric, a.nombre LIKE '%palitos de ajo%'),
      ('Ajo', 0.010::numeric, a.nombre LIKE '%palitos de ajo%'),
      ('Queso Parmesano', 0.025::numeric, a.nombre LIKE '%palitos de ajo%')
    ) x(nombre, cantidad, aplica)
    JOIN insumos i ON lower(trim(i.nombre))=lower(x.nombre)
    WHERE x.aplica
)
INSERT INTO receta_insumos(producto_id, insumo_id, cantidad)
SELECT producto_id, insumo_id, cantidad FROM lineas
ON CONFLICT (producto_id, insumo_id) DO NOTHING;

-- Los combos NO llevan una receta fija de pizza: cada pedido consume la receta de la pizza elegida.
-- Las bebidas consumen el stock de su producto; los acompañamientos fijos se descuentan desde
-- cantidadesPersonalizadas en PedidoService, y su receta se encuentra en el producto del acompañamiento.

-- Recalcular stock teórico según el insumo limitante; no modifica stock de productos sin receta.
UPDATE productos p
SET stock = COALESCE((
    SELECT floor(min(i.stock_actual / NULLIF(r.cantidad,0)))::integer
    FROM receta_insumos r JOIN insumos i ON i.id=r.insumo_id
    WHERE r.producto_id=p.id AND r.cantidad > 0
), p.stock)
WHERE EXISTS (SELECT 1 FROM receta_insumos r WHERE r.producto_id=p.id);

COMMIT;

